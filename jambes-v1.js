const ancienneMiseAJourBandeauJambes = updateShell;
updateShell = function(){
  ancienneMiseAJourBandeauJambes();
  if(state.view === "muscu-jambes" || state.view === "muscu-jambes-detail"){
    bottomNav.classList.add("hidden");
    brandMark.textContent = "M";
    brandEyebrow.textContent = "Ma bibliothèque";
    brandTitle.textContent = "Musculation";
  }
};
const ancienneFonctionListeMusclesAvantJambes = renderMuscuExercises;
renderMuscuExercises = function(){
  ancienneFonctionListeMusclesAvantJambes();
  const ancienBoutonJambes = main.querySelector('[data-muscle="jambes"]');
  if (!ancienBoutonJambes) return;
  const boutonJambes = ancienBoutonJambes.cloneNode(true);
  ancienBoutonJambes.replaceWith(boutonJambes);
  boutonJambes.addEventListener("click", () => {
    state.view = "muscu-jambes";
    state.selected = null;
    render();
  });
};
const ancienneFonctionRenduAvantJambes = render;
render = function(){
  if (state.view === "muscu-jambes") {
    updateShell();
    updateNav();
    return renderMuscuJambes();
  }
  if (state.view === "muscu-jambes-detail") {
    updateShell();
    updateNav();
    return renderMuscuJambesDetail();
  }
  return ancienneFonctionRenduAvantJambes();
};
