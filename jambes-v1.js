function jambesById(id){ return jambesExercices.find(x=>x.id===id); }
function jambesPhotoMarkup(exercice,detail=false){
  const cls = detail ? "muscu-jambes-fiche-photo" : "muscu-jambes-photo";
  return `<div class="${cls}"><img src="${exercice.image}" alt="${esc(exercice.titre)}" loading="lazy" decoding="async"></div>`;
}
function renderMuscuJambes(){
  const cards = jambesExercices.map(exercice => `
    <button class="muscu-jambes-card" type="button" data-jambes-id="${exercice.id}" aria-label="Ouvrir la fiche ${esc(exercice.titre)}">
      ${jambesPhotoMarkup(exercice,false)}
    </button>`).join("");
  main.innerHTML = `
    <section class="panel muscu-jambes-v1">
      <button class="back-chip" id="muscuJambesBack">← Retour</button>
      <header class="panel-header">
        <div>
          <p class="section-kicker">Exercices</p>
          <h2>Jambes</h2>
          <p>10 exercices pour renforcer les jambes à la maison</p>
        </div>
      </header>
      <div class="muscu-jambes-list">${cards}</div>
    </section>`;
  document.getElementById("muscuJambesBack")?.addEventListener("click", ()=>{ state.view = "muscu-exercises"; render(); });
  main.querySelectorAll("[data-jambes-id]").forEach(btn => btn.addEventListener("click", ()=>{
    state.view = "muscu-jambes-detail";
    state.selected = btn.dataset.jambesId;
    render();
  }));
}
