const ancienneMiseAJourBandeauAbdominaux = updateShell;
updateShell = function(){
  ancienneMiseAJourBandeauAbdominaux();
  if(state.view === "muscu-abdominaux" || state.view === "muscu-abdominaux-detail"){
    bottomNav.classList.add("hidden");
    brandMark.textContent = "M";
    brandEyebrow.textContent = "Ma bibliothèque";
    brandTitle.textContent = "Musculation";
  }
};
const ancienneFonctionListeMusclesAvantAbdominaux = renderMuscuExercises;
renderMuscuExercises = function(){
  ancienneFonctionListeMusclesAvantAbdominaux();
  const ancienBoutonAbdominaux = main.querySelector('[data-muscle="abdominaux"]');
  if (!ancienBoutonAbdominaux) return;
  const boutonAbdominaux = ancienBoutonAbdominaux.cloneNode(true);
  ancienBoutonAbdominaux.replaceWith(boutonAbdominaux);
  boutonAbdominaux.addEventListener("click", () => {
    state.view = "muscu-abdominaux";
    state.selected = null;
    render();
  });
};
const ancienneFonctionRenduAvantAbdominaux = render;
render = function(){
  if (state.view === "muscu-abdominaux") {
    updateShell();
    updateNav();
    return renderMuscuAbdominaux();
  }
  if (state.view === "muscu-abdominaux-detail") {
    updateShell();
    updateNav();
    return renderMuscuAbdominauxDetail();
  }
  return ancienneFonctionRenduAvantAbdominaux();
};
