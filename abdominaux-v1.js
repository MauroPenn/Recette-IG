function abdominauxById(id){ return abdominauxExercices.find(x=>x.id===id); }
function abdominauxPhotoMarkup(exercice,detail=false){
  const cls = detail ? "muscu-abdominaux-fiche-photo" : "muscu-abdominaux-photo";
  return `<div class="${cls}"><img src="${exercice.image}" alt="${esc(exercice.titre)}" loading="lazy" decoding="async"></div>`;
}
function renderMuscuAbdominaux(){
  const cards = abdominauxExercices.map(exercice => `
    <button class="muscu-abdominaux-card" type="button" data-abdominaux-id="${exercice.id}" aria-label="Ouvrir la fiche ${esc(exercice.titre)}">
      ${abdominauxPhotoMarkup(exercice,false)}
    </button>`).join("");
  main.innerHTML = `
    <section class="muscu-biceps-v1 muscu-abdominaux-v1" aria-label="Exercices Abdominaux">
      <button type="button" class="muscu-back-pill muscu-biceps-back" id="muscuAbdominauxBack" aria-label="Retour aux groupes musculaires">
        <span class="muscu-back-arrow">←</span><span>Retour</span>
      </button>
      <div class="muscu-biceps-heading">
        <div class="muscu-biceps-icon" aria-hidden="true">⌁</div>
        <div>
          <div class="muscu-biceps-kicker">EXERCICES</div>
          <h2>Abdominaux</h2>
          <p>10 exercices pour renforcer les abdominaux à la maison</p>
        </div>
      </div>
      <div class="muscu-abdominaux-list">${cards}</div>
    </section>`;
  document.getElementById("muscuAbdominauxBack")?.addEventListener("click", ()=>{ state.view = "muscu-exercises"; render(); });
  main.querySelectorAll("[data-abdominaux-id]").forEach(btn => btn.addEventListener("click", ()=>{
    state.view = "muscu-abdominaux-detail";
    state.selected = btn.dataset.abdominauxId;
    render();
  }));
}
